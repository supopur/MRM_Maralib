#!/usr/bin/env python3
"""
generate_dvi_lut.py - Look-Up Table generator for Whelen DVI style cosine easing.

Generates a precomputed symmetric cosine ease-in-out look-Up table:
- y = (1 - cos(pi * t)) / 2 for t in [0, 1]
- Maps [0, 255] to [0, 65535].
"""

import argparse
import math
import sys
from pathlib import Path


def generate_lut(size: int = 256, max_val: int = 65535) -> list[int]:
    table = []
    for i in range(size):
        fraction = i / (size - 1)
        # Cosine ease-in-out: starts with derivative 0, finishes with derivative 0
        ease = (1.0 - math.cos(math.pi * fraction)) / 2.0
        val = round(ease * max_val)
        val = max(0, min(max_val, val))
        table.append(val)
    return table


def format_c_header(table: list[int], size: int, max_val: int) -> str:
    lines = [
        "//",
        "// DviLut.h - Auto-generated Easing Look-Up Table for DVI (Dynamic Variable Intensity)",
        f"// Generated by generate_dvi_lut.py (Size: {size}, Max: {max_val})",
        "// Symmetric cosine ease-in-out curve for smooth LED fading and breathing",
        "//",
        "",
        "#ifndef MAJAK_DVILUT_H",
        "#define MAJAK_DVILUT_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define DVI_LUT_SIZE       {size}U",
        f"#define DVI_LUT_MAX_VALUE  {max_val}U",
        "",
        f"static const uint16_t DVI_EASE_LUT[DVI_LUT_SIZE] = {{",
    ]

    cols = 8
    for i in range(0, size, cols):
        chunk = table[i:i + cols]
        formatted = ", ".join(f"{val:5d}U" for val in chunk)
        if i + cols < size:
            formatted += ","
        lines.append(f"    {formatted}")

    lines.extend([
        "};",
        "",
        "#endif // MAJAK_DVILUT_H",
        "",
    ])

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate cosine ease-in-out LUT for DVI transitions.")
    parser.add_argument("--size", type=int, default=256, help="LUT size (default: 256)")
    parser.add_argument("--max", type=int, default=65535, help="Maximum table value (default: 65535)")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "DviLut.h",
        help="Output header file path",
    )

    args = parser.parse_args()

    table = generate_lut(size=args.size, max_val=args.max)
    content = format_c_header(table, size=args.size, max_val=args.max)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    print(f"Generated {args.output} successfully.")


if __name__ == "__main__":
    main()
